#!/usr/bin/env python3
"""Regenerates tests/test-am-beta-injection-ref.h (numpy only).

Mirrors epyc-inference-research scripts/benchmark/attention_matching.py (HighestAttnKeys-fast,
score='max'): top-t keys by max attention weight, beta = log(clamp(lstsq(exp_scores[:,sel], sum_exp), 1e-12)),
C2 = lstsq(softmax(Q C1^T/sqrt(d) + beta), softmax(Q K^T/sqrt(d)) V). The emitted `out` is
softmax(Q C1^T/sqrt(d) + beta) @ C2, the compact-cache attention output the C++ test must reproduce.
"""
import sys
import numpy as np

T, d, n, t = 8, 4, 12, 4
rng = np.random.default_rng(20261119)
K = rng.standard_normal((T, d)).astype(np.float32)
V = rng.standard_normal((T, d)).astype(np.float32)
Q = rng.standard_normal((n, d)).astype(np.float32)

def sm(s):
    e = np.exp(s - s.max(1, keepdims=True))
    return e, e / e.sum(1, keepdims=True)

s = (Q.astype(np.float64) @ K.T.astype(np.float64)) / np.sqrt(d)
e, w = sm(s)
sel = np.sort(np.argsort(-w.max(0))[:t])
B = np.linalg.lstsq(e[:, sel], e.sum(1), rcond=None)[0].clip(min=1e-12)
beta = np.log(B)
C1 = K[sel]
_, X = sm((Q.astype(np.float64) @ C1.T.astype(np.float64)) / np.sqrt(d) + beta)
C2 = np.linalg.lstsq(X, w @ V.astype(np.float64), rcond=None)[0].astype(np.float32)
beta = beta.astype(np.float32)
_, X = sm((Q.astype(np.float64) @ C1.T.astype(np.float64)) / np.sqrt(d) + beta.astype(np.float64))
out = (X @ C2.astype(np.float64)).astype(np.float32)
_, X0 = sm((Q.astype(np.float64) @ C1.T.astype(np.float64)) / np.sqrt(d))
out0 = (X0 @ C2.astype(np.float64)).astype(np.float32)

def arr(name, a):
    flat = ", ".join(f"{x:.9g}f" for x in np.asarray(a).ravel())
    return f"static const float {name}[{np.asarray(a).size}] = {{ {flat} }};\n"

with open(sys.argv[1] if len(sys.argv) > 1 else "tests/test-am-beta-injection-ref.h", "w") as f:
    f.write("// GENERATED by tests/am-beta-reference.py (numpy). Do not edit.\n#pragma once\n")
    f.write(f"enum {{ AM_REF_T = {T}, AM_REF_D = {d}, AM_REF_N = {n}, AM_REF_TC = {t} }};\n")
    f.write(arr("AM_REF_Q", Q)); f.write(arr("AM_REF_C1", C1)); f.write(arr("AM_REF_BETA", beta))
    f.write(arr("AM_REF_C2", C2)); f.write(arr("AM_REF_OUT", out)); f.write(arr("AM_REF_OUT_NOBETA", out0))
print("sel", sel.tolist(), "beta", beta, "max|out-out0|", np.abs(out - out0).max())
